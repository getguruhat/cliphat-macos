    /// The language code the app uses: "es", "de", "fr", "it", "pt", "ja", "zh-Hans", "ko", or "en".
    /// Traditional Chinese has no translation yet, so it falls back to English (as on Windows).
    static func code(for identifier: String) -> String {
        let locale = Locale(identifier: identifier)
        let language = locale.language.languageCode?.identifier ?? "en"
        if language == "zh" {
            let script = locale.language.script?.identifier
            let region = locale.language.region?.identifier
            if script == "Hans" || (script == nil && (region == nil || region == "CN" || region == "SG")) { return "zh-Hans" }
            return "en"
        }
        return tables[language] != nil ? language : "en"
    }

    /// The language the app shows; the checks switch it with `use(_:)`.
    private(set) static var current: String = code(for: Locale.preferredLanguages.first ?? "en")
    static func use(_ identifier: String) { current = code(for: identifier) }

    static func text(_ key: Key, _ values: String..., language: String? = nil) -> String {
        fill(template(key, language: language ?? current), values)
    }
    static func template(_ key: Key, language: String) -> String {
        tables[language]?[key] ?? english[key] ?? key.rawValue
    }
    static func fill(_ template: String, _ values: [String]) -> String {
        var result = template
        for (index, value) in values.enumerated() { result = result.replacingOccurrences(of: "{\(index)}", with: value) }
        return result
    }

    /// "1 item" / "5 items".
    static func itemCount(_ count: Int) -> String {
        count == 1 ? text(.oneItem) : text(.items, String(count))
    }
    /// Date headings for older days, such as "October 21".
    static func dayName(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: current == "en" ? "en_US" : current)
        formatter.dateFormat = template(.dayFormat, language: current)
        return formatter.string(from: date)
    }
    /// Every translated language code, for the checks.
    static var codes: [String] { tables.keys.sorted() }

